// dbcs are the three DBC tables the template points into by index.
type dbcs struct {
	castMS   map[uint32]int32      // SpellCastTimes: base cast time in ms
	ranges   map[uint32][2]float32 // SpellRange: min and max yards
	duration map[uint32]int32      // SpellDuration: base duration in ms, -1 for none
}

// readDBCs reads SpellCastTimes.dbc, SpellRange.dbc and SpellDuration.dbc from dir.
func readDBCs(dir string) (dbcs, error) {
	d := dbcs{castMS: map[uint32]int32{}, ranges: map[uint32][2]float32{}, duration: map[uint32]int32{}}
	rec, err := readDBC(filepath.Join(dir, "SpellCastTimes.dbc"), 4) // id, base, perLevel, minimum (DBCStructure.h:536-542)
	if err != nil {
		return d, err
	}
	for _, r := range rec {
		d.castMS[r[0]] = int32(r[1])
	}
	if rec, err = readDBC(filepath.Join(dir, "SpellRange.dbc"), 3); err != nil { // id, min, max (DBCfmt.h:65, DBCStructure.h:565-575)
		return d, err
	}
	for _, r := range rec {
		d.ranges[r[0]] = [2]float32{math.Float32frombits(r[1]), math.Float32frombits(r[2])}
	}
	if rec, err = readDBC(filepath.Join(dir, "SpellDuration.dbc"), 2); err != nil { // id, base ms
		return d, err
	}
	for _, r := range rec {
		d.duration[r[0]] = int32(r[1])
	}
	return d, nil
}

// readDBC reads a WDBC file and returns, per record, its first words (need of them; the
// files hold more, none of which the tool uses). Every field of the three tables is 4 bytes.
func readDBC(path string, need int) ([][]uint32, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return parseDBC(path, b, need)
}

func parseDBC(name string, b []byte, need int) ([][]uint32, error) {
	if len(b) < 20 || string(b[:4]) != "WDBC" {
		return nil, fmt.Errorf("%s: not a WDBC file", name)
	}
	n, fields, size, str := binary.LittleEndian.Uint32(b[4:]), binary.LittleEndian.Uint32(b[8:]), binary.LittleEndian.Uint32(b[12:]), binary.LittleEndian.Uint32(b[16:])
	if int(fields) < need || size != fields*4 {
		return nil, fmt.Errorf("%s: %d fields of %d bytes, want at least %d fields of 4 bytes", name, fields, size, need)
	}
	if uint64(len(b)) != 20+uint64(n)*uint64(size)+uint64(str) {
		return nil, fmt.Errorf("%s: %d bytes for %d records of %d and %d of strings", name, len(b), n, size, str)
	}
	out := make([][]uint32, n)
	for i := range out {
		rec := make([]uint32, need)
		for j := range rec {
			rec[j] = binary.LittleEndian.Uint32(b[20+i*int(size)+j*4:])
		}
		out[i] = rec
	}
	return out, nil
}

var rankText = regexp.MustCompile(`^Rank (\d+)$`)

// metaHeader names the columns of meta.tsv.gz; internal/spells reads them by position.
const metaHeader = "id\trank\tlevel\tbase_level\tmax_level\tpower\tcost\tcost_pct\tcast_ms\trange_min\trange_max\tcooldown_ms\tcategory\tcategory_cd_ms\tgcd_category\tgcd_ms\tschool\tdispel\tmechanic\tduration_ms\tflags\teffect1\teffect2\teffect3\treagents"

// meta returns meta.tsv.gz: a header, a column line, then one line per named spell that has
// anything to say, in id order. Zero values are left empty. Each effect is
// "effect,aura,base,dice,sides,per_level,per_combo_point", trailing empties cut.
func (t table) meta(src []byte, updates int, d dbcs) ([]byte, error) {
	var tsv bytes.Buffer
	fmt.Fprintf(&tsv, "# generated by tools/spellnamegen from %s and the Spell{CastTimes,Range,Duration}.dbc of the server (sha256 %x); DO NOT EDIT\n", origin(src, updates), dbcSum(d))
	fmt.Fprintf(&tsv, "# columns (see internal/spells/meta.go): %s\n", metaHeader)
	for _, id := range t.sortedIDs() {
		r := t.rows[id]
		if r[col["name"]] == "" {
			continue
		}
		line, err := metaLine(id, r, d)
		if err != nil {
			return nil, fmt.Errorf("spell %d: %w", id, err)
		}
		if line != "" {
			tsv.WriteString(line)
			tsv.WriteByte('\n')
		}
	}
	return gzipped(tsv.Bytes())
}

// dbcSum fingerprints the DBC values that were used, so a changed DBC changes the header.
func dbcSum(d dbcs) [8]byte {
	h := sha256.New()
	for _, m := range []map[uint32]int32{d.castMS, d.duration} {
		for _, k := range sortedKeys(m) {
			fmt.Fprintf(h, "%d=%d;", k, m[k])
		}
		h.Write([]byte("|"))
	}
	for _, k := range sortedKeys(d.ranges) {
		fmt.Fprintf(h, "%d=%v;", k, d.ranges[k])
	}
	var out [8]byte
	copy(out[:], h.Sum(nil))
	return out
}

func sortedKeys[V any](m map[uint32]V) []uint32 {
	keys := make([]uint32, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	for i := 1; i < len(keys); i++ { // insertion sort: the tables hold under a hundred ids
		for j := i; j > 0 && keys[j] < keys[j-1]; j-- {
			keys[j], keys[j-1] = keys[j-1], keys[j]
		}
	}
	return keys
}

// num reads an integer column; an empty one is 0.
func num(r []string, c string) (int64, error) {
	s := r[col[c]]
	if s == "" {
		return 0, nil
	}
	v, err := strconv.ParseInt(s, 10, 64)
	if err != nil {
		return 0, fmt.Errorf("%s %q: %w", c, s, err)
	}
	return v, nil
}

// flt reads a float column; an empty one is 0.
func flt(r []string, c string) (float64, error) {
	s := r[col[c]]
	if s == "" {
		return 0, nil
	}
	v, err := strconv.ParseFloat(s, 64)
	if err != nil {
		return 0, fmt.Errorf("%s %q: %w", c, s, err)
	}
	return v, nil
}

// z writes 0 as the empty string, to keep the file small.
func z(v int64) string {
	if v == 0 {
		return ""
	}
	return strconv.FormatInt(v, 10)
}

func zf(v float64) string {
	if v == 0 {
		return ""
	}
	return strconv.FormatFloat(v, 'g', -1, 32)
}

// metaLine is the line for one spell, or "" when it holds nothing but an id.
func metaLine(id uint64, r []string, d dbcs) (string, error) {
	var err error
	n := func(c string) int64 {
		v, e := num(r, c)
		if e != nil && err == nil {
			err = e
		}
		return v
	}
	f := func(c string) float64 {
		v, e := flt(r, c)
		if e != nil && err == nil {
			err = e
		}
		return v
	}
	var rank int64
	if m := rankText.FindStringSubmatch(r[col["nameSubtext"]]); m != nil {
		rank, _ = strconv.ParseInt(m[1], 10, 64)
	}
	var cast int64
	if i := n("castingTimeIndex"); i != 0 {
		cast = int64(d.castMS[uint32(i)])
	}
	var rmin, rmax float64
	if i := n("rangeIndex"); i != 0 {
		rg := d.ranges[uint32(i)]
		rmin, rmax = float64(rg[0]), float64(rg[1])
	}
	var dur int64
	if i := n("durationIndex"); i != 0 {
		dur = int64(d.duration[uint32(i)])
	}
	var fx [3]string
	var effects [3][2]int64
	for i := 0; i < 3; i++ {
		s := strconv.Itoa(i + 1)
		e, a := n("effect"+s), n("effectApplyAuraName"+s)
		effects[i] = [2]int64{e, a}
		if e == 0 && a == 0 {
			continue
		}
		parts := []string{z(e), z(a), z(n("effectBasePoints" + s)), z(n("effectBaseDice" + s)), z(n("effectDieSides" + s)),
			zf(f("effectRealPointsPerLevel" + s)), zf(f("effectPointsPerComboPoint" + s))}
		for len(parts) > 0 && parts[len(parts)-1] == "" {
			parts = parts[:len(parts)-1]
		}
		fx[i] = strings.Join(parts, ",")
	}
	var reagents []string
	for i := 1; i <= 8; i++ {
		s := strconv.Itoa(i)
		if item := n("reagent" + s); item > 0 {
			count := n("reagentCount" + s)
			if count < 1 {
				count = 1
			}
			reagents = append(reagents, fmt.Sprintf("%d*%d", item, count))
		}
	}
	flags := spells.FlagsOf(spells.FlagInput{
		Attributes: uint32(n("attributes")), AttributesEx: uint32(n("attributesEx")), AttributesEx2: uint32(n("attributesEx2")),
		InterruptFlags: uint32(n("interruptFlags")), ChannelInterruptFlags: uint32(n("channelInterruptFlags")),
		Effects: effects,
	})
	if err != nil {
		return "", err
	}
	cols := []string{
		strconv.FormatUint(id, 10), z(rank), z(n("spellLevel")), z(n("baseLevel")), z(n("maxLevel")),
		z(n("powerType")), z(n("manaCost")), z(n("manaCostPercentage")), z(cast), zf(rmin), zf(rmax),
		z(n("recoveryTime")), z(n("category")), z(n("categoryRecoveryTime")), z(n("startRecoveryCategory")), z(n("startRecoveryTime")),
		z(n("school")), z(n("dispel")), z(n("mechanic")), z(dur), z(int64(flags)), fx[0], fx[1], fx[2], strings.Join(reagents, ","),
	}
	if err != nil {
		return "", err
	}
	empty := true
	for _, c := range cols[1:] {
		if c != "" {
			empty = false
		}
	}
	if empty {
		return "", nil
	}
	return strings.Join(cols, "\t"), nil
}
