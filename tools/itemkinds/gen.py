#!/usr/bin/env python3
"""Generates internal/dungeon/itemkinds_gen.go from the core's item_template dump.

  python3 -I tools/itemkinds/gen.py $CORE/sql/base/tw_world_item_template.sql internal/dungeon/itemkinds_gen.go <core sha>

The lists are the entries a pre-run kit check (RemoteOptions.Preflight) recognises: drinks (class 0 items whose first spell is one of
the plain Drink spells), arrows and bullets (class 6), shields (class 4 subclass 6) and the ranged weapons that shoot them (class 2:
bows 2 and crossbows 18 shoot arrows, guns 3 shoot bullets). Deprecated, test and monster items are left out.
"""
import re
import sys

DRINK_SPELLS = {"430", "431", "432", "1133", "1135", "1137", "22734", "24355"}
SKIP = re.compile(r"deprecated|depricated|\btest\b|monster|^zz|\bBKP\b|\(old\)", re.I)


def rows(path):
    txt = open(path, encoding="utf8", errors="replace").read()
    cols = re.findall(r"^  `(\w+)` ", txt.split("CREATE TABLE `item_template`")[1].split(") ENGINE")[0], re.M)
    for m in re.finditer(r"^INSERT INTO `item_template` VALUES (.*);$", txt, re.M):
        s, i, n = m.group(1), 0, len(m.group(1))
        while i < n:
            assert s[i] == "("
            i += 1
            vals = []
            while True:
                if s[i] == "'":
                    j, buf = i + 1, []
                    while True:
                        c = s[j]
                        if c == "\\":
                            buf.append(s[j + 1])
                            j += 2
                            continue
                        if c == "'":
                            if s[j + 1:j + 2] == "'":
                                buf.append("'")
                                j += 2
                                continue
                            break
                        buf.append(c)
                        j += 1
                    vals.append("".join(buf))
                    i = j + 1
                else:
                    j = i
                    while s[j] not in ",)":
                        j += 1
                    vals.append(s[i:j])
                    i = j
                if s[i] == ",":
                    i += 1
                    continue
                i += 1
                break
            yield dict(zip(cols, vals))
            if i < n and s[i] == ",":
                i += 1


def emit(name, doc, entries):
    out = ["// " + doc, "var " + name + " = []uint32{"]
    line = "\t"
    for e in sorted(entries):
        tok = f"{e}, "
        if len(line) + len(tok) > 130:
            out.append(line.rstrip())
            line = "\t"
        line += tok
    out.append(line.rstrip())
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    src, dst, sha = sys.argv[1], sys.argv[2], sys.argv[3]
    drinks, arrows, bullets, shields, arrow_guns, bullet_guns = [], [], [], [], [], []
    for r in rows(src):
        if SKIP.search(r["name"]):
            continue
        e, c, sc = int(r["entry"]), r["class"], r["subclass"]
        if c == "0" and r["spellid_1"] in DRINK_SPELLS:
            drinks.append(e)
        elif c == "6" and sc == "2":
            arrows.append(e)
        elif c == "6" and sc == "3":
            bullets.append(e)
        elif c == "4" and sc == "6":
            shields.append(e)
        elif c == "2" and sc in ("2", "18") and r["inventory_type"] in ("15", "26"):
            arrow_guns.append(e)
        elif c == "2" and sc == "3" and r["inventory_type"] in ("15", "26"):
            bullet_guns.append(e)
    with open(dst, "w") as f:
        f.write(f"// Code generated by tools/itemkinds from tortoise-wow {sha} sql/base/tw_world_item_template.sql; DO NOT EDIT.\n\npackage dungeon\n\n")
        f.write(emit("drinkEntries", "drinkEntries are the drinks: class 0 items whose first spell is a plain Drink spell.", drinks) + "\n")
        f.write(emit("arrowEntries", "arrowEntries are the arrows (class 6 subclass 2).", arrows) + "\n")
        f.write(emit("bulletEntries", "bulletEntries are the bullets (class 6 subclass 3).", bullets) + "\n")
        f.write(emit("shieldEntries", "shieldEntries are the shields (class 4 subclass 6).", shields) + "\n")
        f.write(emit("arrowWeaponEntries", "arrowWeaponEntries are the bows and crossbows (class 2 subclasses 2 and 18, ranged slot).", arrow_guns) + "\n")
        f.write(emit("bulletWeaponEntries", "bulletWeaponEntries are the guns (class 2 subclass 3, ranged slot).", bullet_guns))


main()
