#!/usr/bin/env python3
"""Tests of the knowledge-base rotation generator (tools/kbrotgen/kbrotgen.py).

Run them with (from the module root; not part of `make test`):

  python3 -I -m unittest discover -s tools/kbrotgen -p 'test_*.py'

The fixture is a small KB file and recipe in a temporary module root: no network, no PyYAML beyond what the generator
already needs, and the generated bytes are the same on every run.
"""
import hashlib
import io
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kbrotgen


def text_sha(text):
    return hashlib.sha256(" ".join(text.split()).encode("utf8")).hexdigest()[:12]


MINI_KB = """\
class: Warrior
spec: Protection
role: tank
sources:
- {url: 'https://forum.example.test/p=1', author: A, authority: staff, date: '2024-01-01'}
rotation_single:
- {priority: 1, action: Shield Slam, condition: on cooldown}
rotation_aoe:
- {targets_min: 2, priority: 1, action: Thunder Clap}
cooldowns:
- {name: Shield Wall, use_when: low HP}
"""


def mini_recipe():
    return {
        "name": "kb_mini_warrior",
        "class": "warrior",
        "spec": "protection",
        "role": "tank",
        "kb_file": "classes/yaml/warrior/mini.yaml",
        "preset": "tank_warrior",
        "replaces": ["warrior_tank"],
        "mode": "",
        "notes": "A mini list of the test.",
        "rows": [
            {"from": "rotation_single", "index": 0, "priority": 1,
             "text": "Shield Slam | on cooldown", "text_sha": text_sha("Shield Slam | on cooldown"),
             "entries": [{"id": "shield_slam", "spell": "Shield Slam", "level": 1, "target": "fight"}]},
            {"from": "rotation_aoe", "index": 0, "priority": 1,
             "text": "Thunder Clap", "text_sha": text_sha("Thunder Clap"),
             "entries": [{"id": "thunder_clap", "spell": "Thunder Clap", "level": 6, "target": "fight"}]},
            {"from": "cooldowns", "index": 0, "priority": 1,
             "text": "Shield Wall | low HP", "text_sha": text_sha("Shield Wall | low HP"),
             "entries": [{"id": "shield_wall", "spell": "Shield Wall", "level": 24, "target": "self"}]},
        ],
        "order": ["shield_slam", "thunder_clap", "shield_wall"],
        "oracle": {
            "core": ["Shield Slam"],
            "situational": ["Thunder Clap", "Shield Wall"],
            "never": [],
            "signature": ["Shield Slam"],
            "taunt": ["Taunt"],
        },
    }


class KBrotgenTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        base = Path(self.tmp.name)
        self.kb = base / "kb"
        self.root = base / "repo"
        (self.kb / "classes/yaml/warrior").mkdir(parents=True)
        (self.root / "tools/kbrotgen/recipes").mkdir(parents=True)
        (self.root / "internal/brain/rotations").mkdir(parents=True)
        (self.root / "internal/kbspells/oracle").mkdir(parents=True)
        self.write_kb(MINI_KB)
        self.write_recipe(mini_recipe())

    def write_kb(self, text):
        (self.kb / "classes/yaml/warrior/mini.yaml").write_text(text, encoding="utf8")

    def write_recipe(self, recipe):
        (self.root / "tools/kbrotgen/recipes/kb_mini_warrior.json").write_text(
            json.dumps(recipe, indent=2) + "\n", encoding="utf8")

    def read_recipe(self):
        return json.loads((self.root / "tools/kbrotgen/recipes/kb_mini_warrior.json").read_text(encoding="utf8"))

    def generate(self):
        out, err = io.StringIO(), io.StringIO()
        code = kbrotgen.generate(self.kb, self.root, out=out, err=err)
        return code, out.getvalue(), err.getvalue()

    def test_generates_the_rotation_and_the_class_oracle_byte_stable(self):
        code, out, err = self.generate()
        self.assertEqual(0, code, err)
        rot = self.root / "internal/brain/rotations/kb_mini_warrior.json"
        oracle = self.root / "internal/kbspells/oracle/warrior.json"
        self.assertTrue(rot.exists(), "no rotation")
        self.assertTrue(oracle.exists(), "no oracle")
        first = rot.read_bytes()
        code, out, err = self.generate()
        self.assertEqual(0, code, err)
        self.assertEqual(first, rot.read_bytes(), "the generator is not byte-stable")
        body = json.loads(first)
        self.assertEqual(["shield_slam", "thunder_clap", "shield_wall"], [p["id"] for p in body["priorities"]])
        self.assertEqual("mini.yaml", Path(body["kb"]["file"]).name)
        yaml_bytes = (self.kb / "classes/yaml/warrior/mini.yaml").read_bytes()
        self.assertEqual(hashlib.sha256(yaml_bytes).hexdigest(), body["kb"]["sha256"])
        data = json.loads(oracle.read_text(encoding="utf8"))
        self.assertEqual("warrior", data["class"])
        self.assertEqual("kb_mini_warrior", data["specs"][0]["rotation"])
        self.assertEqual(["Shield Slam"], data["specs"][0]["core"])

    def test_missing_recipe_row_fails(self):
        rec = self.read_recipe()
        rec["rows"] = [r for r in rec["rows"] if r["from"] != "cooldowns"]
        self.write_recipe(rec)
        code, out, err = self.generate()
        self.assertEqual(1, code)
        self.assertIn("cooldowns[0]: the KB row has no recipe row", err)

    def test_changed_text_fails_on_the_stale_sha(self):
        self.write_kb(MINI_KB.replace("action: Shield Slam", "action: Shield Slam now"))
        rec = self.read_recipe()
        rec["rows"][0]["text"] = "Shield Slam now | on cooldown"
        self.write_recipe(rec)  # the text is updated, the text_sha is not
        code, out, err = self.generate()
        self.assertEqual(1, code)
        self.assertIn("text_sha differs", err)

    def test_doubled_order_id_fails(self):
        rec = self.read_recipe()
        rec["order"].append(rec["order"][0])
        self.write_recipe(rec)
        code, out, err = self.generate()
        self.assertEqual(1, code)
        self.assertIn("appears twice", err)


if __name__ == "__main__":
    unittest.main()
